#!/usr/bin/env node
// Generates src/office-js/supported.generated.mts from test/office-js-subset.ts (CR-002 phase I).
//
// The subset file is the Office JS promise (CR-002 section 3.4): every member it declares is
// implemented here, so the set of `Class.member` strings it yields is exactly what a tool may
// assume before running an add-in script. The reader is data-driven: it takes every interface
// in the file, whatever it is called, so that phases which extend the subset (tables, comments,
// content controls) need no change here.
//
//   node scripts/generate-supported.mjs           writes the file
//   node scripts/generate-supported.mjs --check    exits 1 when the file is out of date
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePath = join(root, 'test', 'office-js-subset.ts');
const targetPath = join(root, 'src', 'office-js', 'supported.generated.mts');

/** Drops comments, so that a commented-out member is not read as one. */
function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

/** The body of every `interface Name { ... }` in the text, by name, matched on braces. */
function interfaces(text) {
  const out = [];
  const re = /\binterface\s+([A-Za-z_$][\w$]*)[^{]*\{/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    let depth = 1;
    let i = re.lastIndex;
    for (; i < text.length && depth > 0; i++) {
      if (text[i] === '{') depth++;
      else if (text[i] === '}') depth--;
    }
    out.push([m[1], text.slice(re.lastIndex, i - 1)]);
    re.lastIndex = i;
  }
  return out;
}

/** The member names an interface body declares: properties, methods, optional and readonly alike. */
function members(body) {
  const text = body.replace(/=>/g, '@@');
  const chunks = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '{' || c === '(' || c === '[' || c === '<') depth++;
    else if (c === '}' || c === ')' || c === ']' || c === '>') depth = Math.max(0, depth - 1);
    else if (depth === 0 && (c === ';' || c === ',' || c === '\n')) {
      chunks.push(text.slice(start, i));
      start = i + 1;
    }
  }
  chunks.push(text.slice(start));
  const out = [];
  for (const chunk of chunks) {
    const m = /^\s*(?:readonly\s+)?([A-Za-z_$][\w$]*)\s*\??\s*[:(<]/.exec(chunk);
    if (m && m[1] !== 'new') out.push(m[1]);
  }
  return out;
}

function render(entries) {
  return [
    '// Generated by scripts/generate-supported.mjs from test/office-js-subset.ts. Do not edit.',
    '// Every member the Office JS subset declares, as `Class.member`: what this package implements',
    '// of the Word API (CR-002 sections 3.4 and 3.10). Regenerate with `npm run generate`.',
    '',
    'export const SUBSET_MEMBERS: readonly string[] = [',
    ...entries.map((e) => `  '${e}',`),
    '];',
    '',
  ].join('\n');
}

const source = stripComments(await readFile(sourcePath, 'utf8'));
const entries = new Set();
for (const [name, body] of interfaces(source)) {
  for (const member of members(body)) entries.add(`${name}.${member}`);
}
const rendered = render([...entries].sort());

if (process.argv.includes('--check')) {
  const current = await readFile(targetPath, 'utf8').catch(() => '');
  if (current !== rendered) {
    console.error(`${targetPath} is out of date; run: npm run generate`);
    process.exit(1);
  }
  console.log(`supported.generated.mts is up to date (${entries.size} members)`);
} else {
  await writeFile(targetPath, rendered);
  console.log(`wrote ${targetPath} (${entries.size} members)`);
}
