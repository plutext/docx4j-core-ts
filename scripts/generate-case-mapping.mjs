#!/usr/bin/env node
// Writes src/model/text/caseMapping.generated.mts, the simple uppercase mapping CaseMapping writes w:caps by (CR-012
// section 24.1, D4), from a UnicodeData.txt of a stated version:
//
//   node scripts/generate-case-mapping.mjs <UnicodeData.txt> <version> [--check]
//
// The file is https://www.unicode.org/Public/<version>/ucd/UnicodeData.txt; field 12 of each line is the simple
// uppercase mapping (Java's Character.toUpperCase(int)). JavaScript has none (toUpperCase is the full mapping, and the
// runtime's Unicode version moves with its ICU), so the table is generated at the version docx4j's tests run (JDK 21,
// Unicode 15.0) and committed, as the font tables are. A mapping that would change a code point's UTF-16 length is
// left out (docx4j's guard; none at 15.0). With --check, the file is compared, not written.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const [source, version, flag] = process.argv.slice(2);
if (!source || !/^\d+\.\d+\.\d+$/.test(version ?? '')) {
  console.error('usage: node scripts/generate-case-mapping.mjs <UnicodeData.txt> <version, e.g. 15.0.0> [--check]');
  process.exit(2);
}

const bytes = readFileSync(source);
const pairs = [];
let guarded = 0;
for (const line of bytes.toString('utf8').split('\n')) {
  if (line === '') continue;
  const fields = line.split(';');
  if (fields[12] === '') continue;
  const cp = Number.parseInt(fields[0], 16);
  const upper = Number.parseInt(fields[12], 16);
  if ((cp > 0xffff) !== (upper > 0xffff)) { guarded++; continue; }
  pairs.push([cp, upper]);
}
pairs.sort((a, b) => a[0] - b[0]);

// runs of one delta at one stride (1 or 2): [start, end, delta, stride]
const runs = [];
for (const [cp, upper] of pairs) {
  const delta = upper - cp;
  const last = runs[runs.length - 1];
  if (last && last[2] === delta) {
    const step = cp - last[1];
    if ((last[0] === last[1] && (step === 1 || step === 2)) || (last[0] !== last[1] && step === last[3])) {
      last[3] = step;
      last[1] = cp;
      continue;
    }
  }
  runs.push([cp, cp, delta, 1]);
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const sha256 = createHash('sha256').update(bytes).digest('hex');
const out = `// The simple uppercase mapping of Unicode ${version} (UnicodeData.txt field 12; Java's Character.toUpperCase(int)), for
// CaseMapping (CR-012 section 24.1, D4).
//
// Generated by scripts/generate-case-mapping.mjs from https://www.unicode.org/Public/${version}/ucd/UnicodeData.txt
// (SHA-256 ${sha256}): ${pairs.length} code points in ${runs.length} runs${guarded === 0 ? '' : `, ${guarded} left out by the length guard`}.
// Do not edit; run the script instead.

/** The Unicode version of the table: a later case pair is unmapped until the table is regenerated (WD 0.52's REQ-607). */
export const CASE_MAPPING_UNICODE_VERSION = '${version}';

/**
 * Runs of code points mapped by one delta: \`start, end, delta, stride\` each, by \`start\`; \`end\` is the run's last code
 * point, and every \`stride\`th code point from \`start\` to it maps to itself plus \`delta\`.
 */
export const UPPERCASE_RUNS: readonly number[] = [
${runs.map((r) => `  ${hex(r[0])}, ${hex(r[1])}, ${r[2]}, ${r[3]},`).join('\n')}
];
`;

const target = join(root, 'src', 'model', 'text', 'caseMapping.generated.mts');
if (flag === '--check') {
  if (readFileSync(target, 'utf8') !== out) {
    console.error(`${target} differs from ${source} at ${version}`);
    process.exit(1);
  }
  console.log(`${target}: the same (${pairs.length} code points, ${runs.length} runs)`);
} else {
  writeFileSync(target, out);
  console.log(`${target}: ${pairs.length} code points in ${runs.length} runs from Unicode ${version}${guarded === 0 ? '' : `, ${guarded} guarded`}`);
}
