#!/usr/bin/env node
// CR-001 Phase B step 4: turn docx4j's font data files into TypeScript modules.
//
//   npm run generate:fonts            # reads ../docx4j
//   DOCX4J=/path/to/docx4j npm run generate:fonts
//
// Four resources become three committed modules under src/model/fonts/.  Nothing here
// decides anything: each module is the file's rows, in the file's order, so that the port
// and docx4j read the same table (docx4j CR-017 phase 0 put the table in a file for exactly
// this reason).
//
//   org/docx4j/fonts/font-substitutes.xml
//       -> substitutions.generated.mts  SUBSTITUTE_ROWS (Mapper.addMetricallyCompatibleSubstitutes)
//   org/docx4j/fonts/substitutions/FontSubstitutions.xml
//       -> substitutions.generated.mts  VCL_ENTRIES (FontFallback's class and candidate lists)
//   org/docx4j/fonts/microsoft/MicrosoftFonts.xml
//       -> families.generated.mts       MS_FONT_NAMES, MS_FONTS_WITH_BOLD (Mapper.hasBoldFace,
//                                       the no-bold-face families; Mapper.isKnownFamily)
//   org/docx4j/fonts/word-line-metrics.properties
//       -> families.generated.mts       LINE_METRIC_FAMILIES, EAST_ASIAN_FAMILIES
//   org/docx4j/openpackaging/parts/WordprocessingML/theme-{2007,2013,2023}.xml
//       -> themes.generated.mts         the three Office themes docx4j supplies
//
// The generated headers record the docx4j commit this ran against; `git -C ../docx4j rev-parse
// HEAD` is read where the checkout is a git repository.
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
// ../docx4j beside this checkout; DOCX4J=... where it is not (a git worktree, say)
const docx4j = process.env.DOCX4J ?? join(root, '..', 'docx4j');
const resources = join(docx4j, 'docx4j-core', 'src', 'main', 'resources');
const out = join(root, 'src', 'model', 'fonts');

function commit() {
  try {
    return execFileSync('git', ['-C', docx4j, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

const COMMIT = commit();

function header(what, sources) {
  return `// ${what}\n`
    + `//\n`
    + `// Generated by scripts/generate-substitutions.mjs from docx4j ${COMMIT}:\n`
    + sources.map((s) => `//   ${s}\n`).join('')
    + `// Do not edit; run \`npm run generate:fonts\` instead.\n`;
}

const json = (v) => JSON.stringify(v);

// --------------------------------------------------------------------- a small XML reader
//
// The three XML files are hand-maintained data with no namespaces, no mixed content and no
// entities beyond the five predefined ones, so a regular-expression reader is enough and this
// script stays dependency-free (docx4j's own FontSubstitutionTable reads its file with a plain
// DOM parser for the same reason).

function unescapeXml(s) {
  return s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'").replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&amp;/g, '&');
}

/** Every `<tag ...>...</tag>` or `<tag ... />` at any depth, as `{ attrs, body }`. */
function* elements(xml, tag) {
  const re = new RegExp(`<${tag}(\\s[^>]*?)?(/)?>`, 'g');
  let m;
  while ((m = re.exec(xml)) !== null) {
    const attrs = attributes(m[1] ?? '');
    if (m[2]) { yield { attrs, body: '' }; continue; }
    const end = xml.indexOf(`</${tag}>`, re.lastIndex);
    yield { attrs, body: end < 0 ? '' : xml.slice(re.lastIndex, end) };
  }
}

function attributes(text) {
  const attrs = {};
  const re = /([A-Za-z_:][\w.:-]*)\s*=\s*"([^"]*)"/g;
  let m;
  while ((m = re.exec(text)) !== null) attrs[m[1]] = unescapeXml(m[2]);
  return attrs;
}

/** The text of the first `<tag>` directly inside `body`, or undefined. */
function child(body, tag) {
  const m = new RegExp(`<${tag}\\s*/>|<${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</${tag}>`).exec(body);
  if (!m) return undefined;
  return m[1] === undefined ? '' : unescapeXml(m[1]).trim();
}

// ------------------------------------------------------------------ font-substitutes.xml

async function substituteRows() {
  const xml = await readFile(join(resources, 'org/docx4j/fonts/font-substitutes.xml'), 'utf8');
  // only the <substitutes> block: <scriptSubstitutes> and <widthFactors> serve the glyph
  // coverage pass and the width scaling, neither of which this CR ports
  const block = /<substitutes>([\s\S]*?)<\/substitutes>/.exec(xml);
  if (!block) throw new Error('no <substitutes> block in font-substitutes.xml');
  const rows = [];
  for (const { attrs, body } of elements(block[1], 'font')) {
    const substitutes = [];
    for (const s of elements(body, 'substitute')) {
      substitutes.push({ font: s.attrs.font, quality: s.attrs.quality, error: s.attrs.error ?? null });
    }
    rows.push({ documentFont: attrs.name, substitutes });
  }
  if (rows.length === 0) throw new Error('no rows in font-substitutes.xml');
  return rows;
}

// -------------------------------------------------------------- substitutions/FontSubstitutions.xml

async function vclEntries() {
  const xml = await readFile(join(resources, 'org/docx4j/fonts/substitutions/FontSubstitutions.xml'), 'utf8');
  const entries = {};
  for (const { attrs, body } of elements(xml, 'replace')) {
    if (!attrs.name) continue;
    entries[attrs.name] = {
      substFonts: child(body, 'SubstFonts') || '',
      fontType: child(body, 'FontType') || '',
      fontWidth: child(body, 'FontWidth') || '',
    };
  }
  if (Object.keys(entries).length === 0) throw new Error('no <replace> entries in FontSubstitutions.xml');
  return entries;
}

// ------------------------------------------------------------- microsoft/MicrosoftFonts.xml

async function microsoftFonts() {
  const xml = await readFile(join(resources, 'org/docx4j/fonts/microsoft/MicrosoftFonts.xml'), 'utf8');
  const names = [];
  const withBold = [];
  for (const { attrs, body } of elements(xml, 'font')) {
    if (!attrs.name) continue;
    names.push(attrs.name);
    if (/<bold[\s/>]/.test(body)) withBold.push(attrs.name);
  }
  if (names.length === 0) throw new Error('no <font> entries in MicrosoftFonts.xml');
  return { names, withBold };
}

// --------------------------------------------------------- word-line-metrics.properties

async function lineMetricFamilies() {
  const text = await readFile(join(resources, 'org/docx4j/fonts/word-line-metrics.properties'), 'utf8');
  const families = [];
  const eastAsian = [];
  for (const line of text.split(/\r?\n/)) {
    if (line.length === 0 || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 0) continue;
    // a java.util.Properties key escapes its spaces
    const key = line.slice(0, eq).replace(/\\ /g, ' ').trim().toLowerCase();
    const fields = line.slice(eq + 1).split(';');
    families.push(key);
    // optional field 7 (index 6): the OS/2 code-page bits call the family East Asian
    if (fields.length > 6 && fields[6].trim() !== '0' && fields[6].trim() !== '') eastAsian.push(key);
  }
  if (families.length === 0) throw new Error('no families in word-line-metrics.properties');
  return { families, eastAsian };
}

// ------------------------------------------------------------------------- theme parts

async function themes() {
  const dir = 'org/docx4j/openpackaging/parts/WordprocessingML';
  const result = {};
  for (const value of ['2007', '2013', '2023']) {
    result[value] = await readFile(join(resources, dir, `theme-${value}.xml`), 'utf8');
  }
  return result;
}

// ------------------------------------------------------------------------------- write

const rows = await substituteRows();
const vcl = await vclEntries();
const ms = await microsoftFonts();
const metrics = await lineMetricFamilies();
const themeXml = await themes();

const substitutions = header(
  'docx4j\'s font substitution tables: the measured substitute rows, and OpenOffice\'s font'
  + ' classes and candidate lists.',
  [
    'org/docx4j/fonts/font-substitutes.xml (the <substitutes> block; <scriptSubstitutes> and'
    + ' <widthFactors> serve the glyph-coverage and width passes, which CR-001 Phase B does not port)',
    'org/docx4j/fonts/substitutions/FontSubstitutions.xml',
  ],
) + `
/** One open substitute for a document font, with what docx4j measured of it. */
export interface Substitute {
  /** The physical font's name, as a font registry keys it ("Carlito Regular"). */
  readonly font: string;
  /** \`metric\` (Word's advances), \`measured\` (the closest face measured against Word's own
   *  PDF), or \`class\` (a face of the same class only). */
  readonly quality: 'metric' | 'measured' | 'class';
  /** What was measured, in the words of the comment it came from; null for a class substitute. */
  readonly error: string | null;
}

/** A document font and its substitutes, best first. */
export interface SubstituteRow {
  readonly documentFont: string;
  readonly substitutes: readonly Substitute[];
}

/** \`font-substitutes.xml\`'s \`<substitutes>\` rows, in the file's order, which is the order
 *  \`Mapper.addMetricallyCompatibleSubstitutes\` takes them in. */
export const SUBSTITUTE_ROWS: readonly SubstituteRow[] = ${json(rows)};

/** One \`<replace>\` of \`FontSubstitutions.xml\` (OpenOffice's VCL.xcu, transformed). */
export interface VclEntry {
  /** \`;\`-separated short keys, closest first. */
  readonly substFonts: string;
  /** \`,\`-separated words: Default, SansSerif, Serif, Fixed, Typewriter, CJK, Symbol, ... */
  readonly fontType: string;
  /** Normal, Condensed, Expanded ... */
  readonly fontWidth: string;
}

/** \`FontSubstitutions.xml\`'s entries, keyed as that file keys them: the font's name
 *  lower-cased with everything but letters and digits removed. */
export const VCL_ENTRIES: Readonly<Record<string, VclEntry>> = ${json(vcl)};
`;

const families = header(
  'The font families docx4j\'s own tables know: which have a bold face of their own, and which'
  + ' have Word line metrics recorded.',
  [
    'org/docx4j/fonts/microsoft/MicrosoftFonts.xml (149 families)',
    'org/docx4j/fonts/word-line-metrics.properties (512 families)',
  ],
) + `
/** The families \`MicrosoftFonts.xml\` lists, as it writes them.  \`MicrosoftFontsRegistry\`
 *  keys that map by the name exactly, so the lookup is case-sensitive here too. */
export const MS_FONT_NAMES: readonly string[] = ${json(ms.names)};

/** Those of {@link MS_FONT_NAMES} whose entry has a \`<bold>\` element.  A family in the
 *  registry without one has no bold face of its own (Franklin Gothic Book), which is what
 *  \`Mapper.hasBoldFace\` answers on. */
export const MS_FONTS_WITH_BOLD: readonly string[] = ${json(ms.withBold)};

/** The families \`word-line-metrics.properties\` holds, lower-cased. */
export const LINE_METRIC_FAMILIES: readonly string[] = ${json(metrics.families)};

/** Those of {@link LINE_METRIC_FAMILIES} the table's optional field 7 flags East Asian. */
export const EAST_ASIAN_FAMILIES: readonly string[] = ${json(metrics.eastAsian)};
`;

const theme = header(
  'The Office themes docx4j supplies to a package that has none, one per value of'
  + ' `docx4j.fonts.defaultTheme`.',
  ['org/docx4j/openpackaging/parts/WordprocessingML/theme-{2007,2013,2023}.xml'],
) + `
/** Office 2007 to 2010: Cambria / Calibri. */
export const THEME_2007_XML = ${json(themeXml['2007'])};

/** Office 2013 to 2022: Calibri Light / Calibri. */
export const THEME_2013_XML = ${json(themeXml['2013'])};

/** Word 365: Aptos Display / Aptos. */
export const THEME_2023_XML = ${json(themeXml['2023'])};
`;

await writeFile(join(out, 'substitutions.generated.mts'), substitutions);
await writeFile(join(out, 'families.generated.mts'), families);
await writeFile(join(out, 'themes.generated.mts'), theme);

console.log(`docx4j ${COMMIT}`);
console.log(`  substitutions.generated.mts  ${rows.length} substitute rows, ${Object.keys(vcl).length} VCL entries`);
console.log(`  families.generated.mts       ${ms.names.length} Microsoft families (${ms.withBold.length} with a bold face), `
  + `${metrics.families.length} line-metric families (${metrics.eastAsian.length} East Asian)`);
console.log(`  themes.generated.mts         3 themes`);
