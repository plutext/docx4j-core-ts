#!/usr/bin/env node
// Writes src/opc/repair/wmlNames.generated.mts, every element name the WordprocessingML schema declares (CR-026 section 3.7), from
// docx4j's wml.xsd. A walk of the model's classes would miss a name with a simple type and no class, such as w:uniqueTag:
//
//   node scripts/generate-wml-names.mjs <wml.xsd> [--check]
//
// --check compares with the committed file and writes nothing.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [xsdPath, flag] = process.argv.slice(2);
if (!xsdPath) throw new Error('Give the path of wml.xsd');
const xsd = readFileSync(xsdPath);
const names = [...new Set([...xsd.toString('utf8').matchAll(/<xsd:element\s+name="([^"]+)"/g)].map((m) => m[1]))].sort();
const lines = [];
for (let i = 0; i < names.length; i += 8) lines.push(`  ${names.slice(i, i + 8).map((n) => `'${n}'`).join(', ')},`);
const text = `// Generated by scripts/generate-wml-names.mjs from docx4j's wml.xsd (sha256 ${createHash('sha256').update(xsd).digest('hex').slice(0, 16)}). Do not edit.
/** Every element name the WordprocessingML schema declares: ${names.length}. */
export const WML_ELEMENT_NAMES: ReadonlySet<string> = new Set([
${lines.join('\n')}
]);
`;
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'opc', 'repair', 'wmlNames.generated.mts');
if (flag === '--check') {
  if (readFileSync(out, 'utf8') !== text) { console.error('wmlNames.generated.mts differs from the schema'); process.exit(1); }
  console.log(`${names.length} names agree`);
} else {
  writeFileSync(out, text);
  console.log(`${names.length} names written`);
}
